export function searchRoles(query, maxResults = 8) {
  if (!query || !query.trim()) return [];
  const normalized = query.toLowerCase().trim();
  const startsWith = AVAILABLE_ROLES.filter(r => 
    r.toLowerCase().startsWith(normalized)
  );
  const contains = AVAILABLE_ROLES.filter(r => 
    r.toLowerCase().includes(normalized) && !r.toLowerCase().startsWith(normalized)
  );
  return [...startsWith, ...contains].slice(0, maxResults);
}
